import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const METEOCON_NAMES = [
  "clear-day",
  "clear-night",
  "partly-cloudy-day",
  "partly-cloudy-night",
  "overcast-day",
  "overcast-night",
  "cloudy",
  "fog-day",
  "fog-night",
  "haze-day",
  "haze-night",
  "drizzle",
  "rain",
  "sleet",
  "snow",
  "thunderstorms-day",
  "thunderstorms-night",
  "not-available",
  "thermometer",
  "raindrop",
] as const;

const ANIMATED_METEOCONS = "@meteocons/svg/monochrome";
const STILL_METEOCONS = "@meteocons/svg-static/monochrome";
const ICON_SVGS_MODULE = new URL("../generated/icon-svgs.ts", import.meta.url);
const OWN_ICONS = new URL("../src/icons/", import.meta.url);

const METEOCONS_LICENSE = await readFile(
  fileURLToPath(import.meta.resolve("@meteocons/svg/LICENSE")),
  "utf8",
);
const METEOCONS_NOTICE = `/*! Meteocons (https://github.com/basmilius/meteocons)\n\n${METEOCONS_LICENSE}*/`;

const readMeteocon = (directory: string, name: string) =>
  readFile(
    fileURLToPath(import.meta.resolve(`${directory}/${name}.svg`)),
    "utf8",
  );
const readOwnIcon = (name: string) =>
  readFile(new URL(`${name}.svg`, OWN_ICONS), "utf8");

const meteocons = Object.fromEntries(
  await Promise.all(
    METEOCON_NAMES.map(
      async (name) =>
        [
          name,
          {
            animated: await readMeteocon(ANIMATED_METEOCONS, name),
            still: await readMeteocon(STILL_METEOCONS, name),
          },
        ] as const,
    ),
  ),
);

const iconSvgs = {
  meteocons,
  windCompass: await readOwnIcon("wind-compass"),
  notAvailableMark: await readOwnIcon("not-available"),
};

const GENERATED_NOTICE =
  "// Generated by scripts/write-icon-svgs.ts. Don't edit this file: run `pnpm --filter @weather-widget/widget write-icon-svgs` instead.";

const source = `${GENERATED_NOTICE}\n${METEOCONS_NOTICE}\nexport const ICON_SVGS = ${JSON.stringify(iconSvgs)} as const;\n`;
const prettierConfig = await resolveConfig(fileURLToPath(ICON_SVGS_MODULE));

await writeFile(
  ICON_SVGS_MODULE,
  await format(source, { ...prettierConfig, parser: "typescript" }),
);
